/* =============================================================================
   Contraprova do dashboard de Contratos - lado PROTHEUS (SQL Server / SSMS)
   Empresa 01 (sufixo 010). Janela: ultimos 30 dias.
   Rode bloco a bloco e compare com contraprova_contratos_databricks.sql.
   ============================================================================= */
SET NOCOUNT ON;

DECLARE @INI CHAR(8) = CONVERT(CHAR(8), DATEADD(DAY, -30, GETDATE()), 112);
DECLARE @HOJE CHAR(8) = CONVERT(CHAR(8), GETDATE(), 112);

/* Especie do contrato: 1 = compra (mesma regra da API BIQCTR) */
IF OBJECT_ID('tempdb..#CTR') IS NOT NULL DROP TABLE #CTR;
SELECT C.CN9_FILIAL, C.CN9_NUMERO, C.CN9_REVISA,
       COALESCE(NULLIF(C.CN9_ESPCTR, ''),
                (SELECT MAX(C1.CN1_ESPCTR) FROM CN1010 C1 WHERE C1.D_E_L_E_T_ = ' '
                   AND C1.CN1_CODIGO = C.CN9_TPCTO
                   AND C1.CN1_FILIAL = SUBSTRING(C.CN9_FILIAL, 1, LEN(C1.CN1_FILIAL)))) ESPECIE
INTO #CTR
FROM CN9010 C
WHERE C.D_E_L_E_T_ = ' ';

/* 1) CND duplicada: a API liga CNE x CND sem CND_NUMERO (planilha).
      Se houver mais de um CND por medicao, cada item da CNE e somado N vezes. */
SELECT CND_FILIAL, CND_CONTRA, CND_REVISA, CND_NUMMED, COUNT(*) QTD_CND
FROM CND010
WHERE D_E_L_E_T_ = ' '
GROUP BY CND_FILIAL, CND_CONTRA, CND_REVISA, CND_NUMMED
HAVING COUNT(*) > 1
ORDER BY QTD_CND DESC;

/* 2) Valor dos ultimos 30 dias por especie: mostra se contratos de VENDA estao vazando como compra */
SELECT COALESCE(T.ESPECIE, '(vazio)') ESPECIE, COUNT(*) ITENS, SUM(CNE.CNE_VLTOT) VALOR
FROM CNE010 CNE
JOIN #CTR T ON T.CN9_FILIAL = CNE.CNE_FILIAL AND T.CN9_NUMERO = CNE.CNE_CONTRA AND T.CN9_REVISA = CNE.CNE_REVISA
WHERE CNE.D_E_L_E_T_ = ' ' AND CNE.CNE_DTENT BETWEEN @INI AND @HOJE
GROUP BY T.ESPECIE;

/* 3) Total "limpo" (so CNE + especie compra, sem nenhum outro JOIN) - bate com o bloco 3 do Databricks.
      Separa encerradas x em aberto e com/sem pedido. */
SELECT TRIM(CNE.CNE_FILIAL) FILIAL,
       COUNT(*) ITENS,
       SUM(CNE.CNE_VLTOT) VALOR_TOTAL,
       SUM(CASE WHEN E.ENC = 1 THEN CNE.CNE_VLTOT END) VALOR_ENCERRADAS,
       SUM(CASE WHEN CNE.CNE_PEDIDO <> '' THEN CNE.CNE_VLTOT END) VALOR_COM_PEDIDO
FROM CNE010 CNE
JOIN #CTR T ON T.CN9_FILIAL = CNE.CNE_FILIAL AND T.CN9_NUMERO = CNE.CNE_CONTRA AND T.CN9_REVISA = CNE.CNE_REVISA
OUTER APPLY (SELECT MAX(CASE WHEN CND.CND_DTFIM <> '' THEN 1 ELSE 0 END) ENC FROM CND010 CND
             WHERE CND.D_E_L_E_T_ = ' ' AND CND.CND_FILIAL = CNE.CNE_FILIAL AND CND.CND_CONTRA = CNE.CNE_CONTRA
               AND CND.CND_REVISA = CNE.CNE_REVISA AND CND.CND_NUMMED = CNE.CNE_NUMMED) E
WHERE CNE.D_E_L_E_T_ = ' ' AND CNE.CNE_DTENT BETWEEN @INI AND @HOJE AND T.ESPECIE = '1'
GROUP BY ROLLUP (TRIM(CNE.CNE_FILIAL))
ORDER BY 1;

/* 4) Mesmo valor pelo cabecalho da medicao (CND_VLTOT, data de encerramento) - visao "medicao realizada" */
SELECT TRIM(CND.CND_FILIAL) FILIAL, COUNT(*) MEDICOES, SUM(CND.CND_VLTOT) VALOR
FROM CND010 CND
JOIN #CTR T ON T.CN9_FILIAL = CND.CND_FILIAL AND T.CN9_NUMERO = CND.CND_CONTRA AND T.CN9_REVISA = CND.CND_REVISA
WHERE CND.D_E_L_E_T_ = ' ' AND CND.CND_DTFIM BETWEEN @INI AND @HOJE AND T.ESPECIE = '1'
GROUP BY ROLLUP (TRIM(CND.CND_FILIAL))
ORDER BY 1;

/* 5) Custo efetivo: notas de entrada (SD1) de pedidos com contrato (C7_CONTRA) digitadas nos ultimos 30 dias.
      Este e o numero mais proximo de "custo dos contratos" que o financeiro enxerga. */
SELECT TRIM(D1.D1_FILIAL) FILIAL, COUNT(DISTINCT D1.D1_DOC + D1.D1_SERIE + D1.D1_FORNECE) NOTAS, SUM(D1.D1_TOTAL) VALOR
FROM SD1010 D1
JOIN SC7010 C7 ON C7.D_E_L_E_T_ = ' ' AND C7.C7_FILIAL = D1.D1_FILIAL AND C7.C7_NUM = D1.D1_PEDIDO
              AND C7.C7_ITEM = D1.D1_ITEMPC AND C7.C7_CONTRA <> ''
WHERE D1.D1_DTDIGIT BETWEEN @INI AND @HOJE AND D1.D_E_L_E_T_ = ' '
GROUP BY ROLLUP (TRIM(D1.D1_FILIAL))
ORDER BY 1;

/* 6) As 30 maiores medicoes da janela - compare com o bloco 4 do Databricks */
SELECT TRIM(CNE.CNE_FILIAL) FILIAL, TRIM(CNE.CNE_CONTRA) CONTRATO, TRIM(CNE.CNE_REVISA) REVISAO,
       TRIM(CNE.CNE_NUMMED) MEDICAO, MIN(CNE.CNE_DTENT) DT_ENTREGA, COUNT(*) ITENS, SUM(CNE.CNE_VLTOT) VALOR
FROM CNE010 CNE
JOIN #CTR T ON T.CN9_FILIAL = CNE.CNE_FILIAL AND T.CN9_NUMERO = CNE.CNE_CONTRA AND T.CN9_REVISA = CNE.CNE_REVISA
WHERE CNE.D_E_L_E_T_ = ' ' AND CNE.CNE_DTENT >= @INI AND T.ESPECIE = '1'
GROUP BY CNE.CNE_FILIAL, CNE.CNE_CONTRA, CNE.CNE_REVISA, CNE.CNE_NUMMED
ORDER BY VALOR DESC
OFFSET 0 ROWS FETCH NEXT 30 ROWS ONLY;

/* 7) Medicoes de contratos de compra com item SEM centro de custo (CNE_CC vazio), desde 01/01/2025.
      Uma linha por medicao: quantos itens e quanto valor ficaram sem CC. */
SELECT TRIM(CNE.CNE_FILIAL) FILIAL, TRIM(CNE.CNE_CONTRA) CONTRATO, TRIM(CNE.CNE_REVISA) REVISAO,
       TRIM(CNE.CNE_NUMMED) MEDICAO, MIN(CNE.CNE_DTENT) DT_ENTREGA, MAX(CNE.CNE_PEDIDO) PEDIDO,
       COUNT(*) ITENS, SUM(CASE WHEN CNE.CNE_CC = '' THEN 1 ELSE 0 END) ITENS_SEM_CC,
       SUM(CNE.CNE_VLTOT) VALOR, SUM(CASE WHEN CNE.CNE_CC = '' THEN CNE.CNE_VLTOT ELSE 0 END) VALOR_SEM_CC
FROM CNE010 CNE
JOIN #CTR T ON T.CN9_FILIAL = CNE.CNE_FILIAL AND T.CN9_NUMERO = CNE.CNE_CONTRA AND T.CN9_REVISA = CNE.CNE_REVISA
WHERE CNE.D_E_L_E_T_ = ' ' AND CNE.CNE_DTENT >= '20250101' AND T.ESPECIE = '1'
GROUP BY CNE.CNE_FILIAL, CNE.CNE_CONTRA, CNE.CNE_REVISA, CNE.CNE_NUMMED
HAVING SUM(CASE WHEN CNE.CNE_CC = '' THEN 1 ELSE 0 END) > 0
ORDER BY DT_ENTREGA DESC, VALOR_SEM_CC DESC;
